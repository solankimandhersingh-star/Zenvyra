package com.zenvya.zenvya_customer_service.customer;

import com.zenvya.zenvya_customer_service.security.CurrentUser;
import jakarta.transaction.Transactional;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

@Service
public class CustomerService {

    private final CustomerRepository repository;

    public CustomerService(CustomerRepository repository) {
        this.repository = repository;
    }

    /**
     * Create a new customer.
     *
     * Customer code is generated by the backend.
     *
     * Example:
     * CUST-000001
     * CUST-000002
     * CUST-000003
     */
    @Transactional
    public CustomerResponse create(CustomerCreateRequest request) {

        requireOrganizationAdmin();

        UUID organizationId = CurrentUser.getOrganizationId();

        String customerCode = generateCustomerCode(organizationId);

        LocalDateTime now = LocalDateTime.now();

        Customer customer = new Customer();

        customer.setId(UUID.randomUUID());
        customer.setOrganizationId(organizationId);
        customer.setCustomerCode(customerCode);

        customer.setName(request.getName().trim());
        customer.setEmail(trimToNull(request.getEmail()));
        customer.setMobile(trimToNull(request.getMobile()));
        customer.setTaxNumber(trimToNull(request.getTaxNumber()));
        customer.setBillingAddress(trimToNull(request.getBillingAddress()));
        customer.setShippingAddress(trimToNull(request.getShippingAddress()));

        customer.setStatus("ACTIVE");
        customer.setCreatedAt(now);
        customer.setUpdatedAt(now);

        return toResponse(repository.save(customer));
    }

    /**
     * Update customer details.
     *
     * Customer code cannot be changed.
     */
    @Transactional
    public CustomerResponse update(
            UUID id,
            CustomerUpdateRequest request) {

        requireOrganizationAdmin();

        Customer customer = getOwned(id);

        customer.setName(request.getName().trim());
        customer.setEmail(trimToNull(request.getEmail()));
        customer.setMobile(trimToNull(request.getMobile()));
        customer.setTaxNumber(trimToNull(request.getTaxNumber()));
        customer.setBillingAddress(
                trimToNull(request.getBillingAddress())
        );
        customer.setShippingAddress(
                trimToNull(request.getShippingAddress())
        );

        customer.setUpdatedAt(LocalDateTime.now());

        return toResponse(repository.save(customer));
    }

    /**
     * Get all customers belonging to the logged-in organization.
     *
     * Optional search is performed against customer name.
     */
    public List<CustomerResponse> getAll(
            String search,
            String selectedOrganizationId) {

        UUID organizationId =
                CurrentUser.getOrganizationId(selectedOrganizationId);

        List<Customer> customers;

        if (search == null || search.isBlank()) {

            customers =
                    repository.findAllByOrganizationIdOrderByNameAsc(
                            organizationId
                    );

        } else {

            customers =
                    repository
                            .findAllByOrganizationIdAndNameContainingIgnoreCaseOrderByNameAsc(
                                    organizationId,
                                    search.trim()
                            );
        }

        return customers.stream()
                .map(this::toResponse)
                .toList();
    }

    /**
     * Get one customer belonging to the logged-in organization.
     */
    public CustomerResponse getById(UUID id) {
        return toResponse(getOwned(id));
    }

    /**
     * Enable or disable a customer.
     */
    @Transactional
    public CustomerResponse updateStatus(
            UUID id,
            CustomerStatusUpdateRequest request) {

        requireOrganizationAdmin();

        Customer customer = getOwned(id);

        String status =
                request.getStatus()
                        .trim()
                        .toUpperCase();

        if (!status.equals("ACTIVE")
                && !status.equals("DISABLED")) {

            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST,
                    "Status must be ACTIVE or DISABLED"
            );
        }

        customer.setStatus(status);
        customer.setUpdatedAt(LocalDateTime.now());

        return toResponse(repository.save(customer));
    }

    /**
     * Delete a customer.
     */
    @Transactional
    public void delete(UUID id) {

        requireOrganizationAdmin();

        Customer customer = getOwned(id);

        repository.delete(customer);
    }

    /**
     * Fetch a customer only when it belongs to
     * the currently authenticated organization.
     *
     * This prevents one organization from accessing
     * another organization's customer using the UUID.
     */
    private Customer getOwned(UUID id) {

        UUID organizationId = CurrentUser.getOrganizationId();

        return repository
                .findByIdAndOrganizationId(id, organizationId)
                .orElseThrow(() ->
                        new ResponseStatusException(
                                HttpStatus.NOT_FOUND,
                                "Customer not found"
                        )
                );
    }

    /**
     * Only ORG_ADMIN can create, update, disable/enable
     * or delete customers.
     */
    private void requireOrganizationAdmin() {

        if (!"ORG_ADMIN".equals(CurrentUser.getRole())) {

            throw new ResponseStatusException(
                    HttpStatus.FORBIDDEN,
                    "Only organization admin can perform this action"
            );
        }
    }

    /**
     * Convert blank strings to null.
     */
    private String trimToNull(String value) {

        return value == null || value.isBlank()
                ? null
                : value.trim();
    }

    /**
     * Convert entity to API response.
     */
    private CustomerResponse toResponse(Customer c) {

        CustomerResponse r = new CustomerResponse();

        r.setId(c.getId());
        r.setOrganizationId(c.getOrganizationId());
        r.setCustomerCode(c.getCustomerCode());

        r.setName(c.getName());
        r.setEmail(c.getEmail());
        r.setMobile(c.getMobile());
        r.setTaxNumber(c.getTaxNumber());

        r.setBillingAddress(c.getBillingAddress());
        r.setShippingAddress(c.getShippingAddress());

        r.setStatus(c.getStatus());

        r.setCreatedAt(c.getCreatedAt());
        r.setUpdatedAt(c.getUpdatedAt());

        return r;
    }

    /**
     * Generate the next customer code for the organization.
     *
     * Format:
     *
     * CUST-000001
     * CUST-000002
     * CUST-000003
     */
    private String generateCustomerCode(UUID organizationId) {

        Optional<Customer> latestCustomer =
                repository
                        .findTopByOrganizationIdOrderByCustomerCodeDesc(
                                organizationId
                        );

        int nextNumber = 1;

        if (latestCustomer.isPresent()) {

            String latestCode =
                    latestCustomer
                            .get()
                            .getCustomerCode();

            if (latestCode != null
                    && latestCode.startsWith("CUST-")) {

                String numberPart =
                        latestCode.substring("CUST-".length());

                try {

                    nextNumber =
                            Integer.parseInt(numberPart) + 1;

                } catch (NumberFormatException ignored) {

                    nextNumber = 1;
                }
            }
        }

        return String.format(
                "CUST-%06d",
                nextNumber
        );
    }
}